    hairColor:        pickRandom(HAIR_COLORS).hex,
    beardStyle:       isFemale ? 'none' : pickRandom(BEARD_STYLES).id,
    beardColor:       pickRandom(HAIR_COLORS).hex,
    glasses:          pickRandom(GLASSES_OPTIONS).id,
